// Generates src/contract.gen.ts from the contract (P1-E/E1):
//   argv[2]: tools/list result (JSON: {tools: [{name, inputSchema}]}) of a
//            live `rootmark serve --mcp stdio` — the argument schemas the
//            contract points to (docs/CLIENT_CONTRACT.md §2);
//   argv[3]: docs/CLIENT_CONTRACT.md (§2 tool table, §3 code table).
// Prints the TypeScript module. Fails on a schema construct it does not
// know, on a tool of the server missing from the contract (or the other
// way round): never a silent partial file.
import { readFileSync } from "node:fs";

const [, , toolsPath, contractPath] = process.argv;
if (!toolsPath || !contractPath) {
  console.error("usage: gen-types.mjs <tools_list.json> <CLIENT_CONTRACT.md>");
  process.exit(2);
}
const tools = JSON.parse(readFileSync(toolsPath, "utf8")).tools;
const contract = readFileSync(contractPath, "utf8");
const section = (from, to) => {
  const a = contract.indexOf(`\n## ${from}. `);
  const b = contract.indexOf(`\n## ${to}. `);
  if (a < 0 || b < 0) throw new Error(`contract: no §${from}..§${to}`);
  return contract.slice(a, b);
};
// the tools table: §2 up to §2.1 (P2-0: §2.6 lists HTTP-only endpoints)
const toolsTable = (() => {
  const s = section(2, 3);
  const end = s.indexOf("\n### 2.1 ");
  return end < 0 ? s : s.slice(0, end);
})();
const contractTools = [...toolsTable.matchAll(/^\| `([a-z_]+)` \|/gm)].map((m) => m[1]);
// §2.6: the human channel's own endpoints (never MCP tools)
const httpOnly = (() => {
  const s = section(2, 3);
  const a = s.indexOf("\n### 2.6 ");
  if (a < 0) return [];
  return [...s.slice(a).matchAll(/^\| `([a-z_]+)` \|/gm)].map((m) => m[1]);
})();
const codes = [...section(3, 4).matchAll(/^\| `([a-z_]+)` \| (\d{3}) \|/gm)].map((m) => [m[1], Number(m[2])]);
const names = tools.map((t) => t.name);
const missing = [
  ...names.filter((n) => !contractTools.includes(n)).map((n) => `server tool ${n} not in the contract`),
  ...contractTools.filter((n) => !names.includes(n)).map((n) => `contract tool ${n} not served`),
];
if (missing.length || codes.length === 0) {
  throw new Error(missing.join("; ") || "contract §3: no codes");
}

const pascal = (s) => s.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());
function tsType(name, key, s) {
  const where = `${name}.${key}`;
  // arrays of a simple type (P2-L/L3: `search.path_prefix`)
  const known = new Set(["type", "description", "enum", "minLength", "minimum", "maximum", "items", "minItems", "maxItems"]);
  for (const k of Object.keys(s)) if (!known.has(k)) throw new Error(`${where}: unknown schema key ${k}`);
  if (s.enum) {
    if (s.type !== "string") throw new Error(`${where}: non-string enum`);
    return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  }
  switch (s.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      if (!s.items || s.items.type === "array") throw new Error(`${where}: an array needs items of a simple type`);
      return `${tsType(name, `${key}[]`, s.items)}[]`;
    default:
      throw new Error(`${where}: unknown type ${s.type}`);
  }
}

let out = `// GENERATED by scripts/gen_client_types.sh from the live tools/list of
// \`rootmark serve --mcp stdio\` and docs/CLIENT_CONTRACT.md §2/§3. Do not edit:
// regenerate (\`scripts/gen_client_types.sh\`; \`--check\` in make lint).

/** The tools of the contract (§2), each served as \`POST /v1/<tool>\`. */
export const TOOLS = ${JSON.stringify(contractTools)} as const;
export type ToolName = (typeof TOOLS)[number];

/** The human channel's own endpoints (§2.6), \`POST /v1/<name>\`; never MCP tools. */
export const HTTP_ONLY = ${JSON.stringify(httpOnly)} as const;
export type HttpOnlyName = (typeof HTTP_ONLY)[number];

/** The stable error codes of the contract (§3) and their HTTP status. */
export const ERROR_STATUS = {
${codes.map(([c, s]) => `  ${c}: ${s},`).join("\n")}
} as const;
export type ErrorCode = keyof typeof ERROR_STATUS;
export const ERROR_CODES = Object.keys(ERROR_STATUS) as ErrorCode[];
`;
for (const name of contractTools) {
  const t = tools.find((x) => x.name === name);
  const s = t.inputSchema;
  const top = new Set(["type", "properties", "required", "additionalProperties", "description", "title", "$schema"]);
  for (const k of Object.keys(s)) if (!top.has(k)) throw new Error(`${name}: unknown top-level schema key ${k}`);
  if (s.type !== "object" || s.additionalProperties !== false) throw new Error(`${name}: not a closed object schema`);
  const req = new Set(s.required ?? []);
  for (const r of req) {
    if (!Object.prototype.hasOwnProperty.call(s.properties ?? {}, r)) throw new Error(`${name}: required ${r} is not a property`);
  }
  const props = Object.entries(s.properties ?? {});
  const doc = `\n/** \`${name}\` arguments (closed: an unknown field is \`invalid_arguments\`). */\n`;
  if (props.length === 0) {
    out += `${doc}export type ${pascal(name)}Args = Record<string, never>;\n`;
    continue;
  }
  out += `${doc}export interface ${pascal(name)}Args {\n`;
  for (const [k, p] of props) {
    if (p.description) out += `  /** ${p.description.replace(/\*\//g, "* /")} */\n`;
    out += `  ${k}${req.has(k) ? "" : "?"}: ${tsType(name, k, p)};\n`;
  }
  out += `}\n`;
}
out += `\n/** Arguments by tool. */\nexport interface ToolArgs {\n${contractTools.map((n) => `  ${n}: ${pascal(n)}Args;`).join("\n")}\n}\n`;
process.stdout.write(out);
